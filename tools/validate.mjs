// Validate every adapter in adapters/ and print a coverage table.
// Usage: node tools/validate.mjs [--md]
import { readdirSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "adapters");

const MODULES = ["settings_sweep", "recordings_purge", "app_audit", "do_not_sell"];
const ACTIONS = ["toggle", "delete", "revoke", "submit_form", "manual"];
const RISKS = ["low", "medium", "high"];
// Optional, shown to people on the guided page (the agent uses find/recommended).
const HUMAN = ["heads_up", "say"];
const REQUIRED = ["id", "module", "title", "find", "recommended", "action", "risk", "reversible"];

const errors = [];
const ids = new Set();
const adapters = [];

for (const file of readdirSync(dir).filter((f) => f.endsWith(".yaml")).sort()) {
  let doc;
  try {
    doc = YAML.parse(readFileSync(join(dir, file), "utf8"));
  } catch (e) {
    errors.push(`${file}: YAML parse error: ${e.message}`);
    continue;
  }
  const where = (c, msg) => errors.push(`${file}${c ? ` [${c.id ?? "?"}]` : ""}: ${msg}`);
  for (const k of ["platform", "name", "domains", "checks"]) if (doc[k] === undefined) where(null, `missing "${k}"`);
  if (doc.blurb != null && typeof doc.blurb !== "string") where(null, `"blurb" must be text`);
  if (!Array.isArray(doc.checks) || doc.checks.length === 0) { where(null, "needs at least one check"); continue; }

  for (const c of doc.checks) {
    for (const k of REQUIRED) if (c[k] === undefined) where(c, `missing "${k}"`);
    if (c.id && !c.id.startsWith(`${doc.platform === "do_not_sell" ? "dns" : doc.platform}.`))
      where(c, `id should start with "${doc.platform}."`);
    if (ids.has(c.id)) where(c, "duplicate id");
    ids.add(c.id);
    if (!MODULES.includes(c.module)) where(c, `module must be one of ${MODULES.join(", ")}`);
    if (!ACTIONS.includes(c.action)) where(c, `action must be one of ${ACTIONS.join(", ")}`);
    if (!RISKS.includes(c.risk)) where(c, `risk must be one of ${RISKS.join(", ")}`);
    for (const k of HUMAN) if (c[k] != null && (typeof c[k] !== "string" || !c[k].trim())) where(c, `"${k}" must be non-empty text`);
    if (c.action === "delete" && c.reversible !== false) where(c, "delete actions must set reversible: false");
    if (c.action === "delete" && c.risk === "low") where(c, "delete actions must be medium or high risk");
    if (c.url && c.url !== "per_site") {
      try {
        const host = new URL(c.url).hostname;
        const ok = doc.domains.includes("*") || doc.domains.some((d) => host === d || host.endsWith(`.${d}`));
        if (!ok) where(c, `url host ${host} is not in the adapter's domains list`);
      } catch { where(c, `bad url ${c.url}`); }
    }
  }
  adapters.push({ file, ...doc });
}

if (errors.length) {
  console.error(`✗ ${errors.length} problem(s):\n  ` + errors.join("\n  "));
  process.exit(1);
}

// Coverage table
const rows = adapters.map((a) => {
  const n = (m) => a.checks.filter((c) => c.module === m).length || "";
  return [a.name, ...MODULES.map(n), a.verified ? `yes (${a.last_checked})` : "not yet"];
});
const header = ["Platform", "Settings", "Recordings", "Apps", "Do not sell", "Verified on a live account"];

if (process.argv.includes("--md")) {
  console.log("# Coverage\n\nGenerated by `npm run coverage`. A platform is verified once a contributor has run every check on a live account.\n");
  console.log(`| ${header.join(" | ")} |\n|${header.map(() => "---").join("|")}|`);
  for (const r of rows) console.log(`| ${r.join(" | ")} |`);
  console.log(`\n**${ids.size} checks across ${adapters.length} adapters.**`);
} else {
  console.log(`✓ ${adapters.length} adapters, ${ids.size} checks valid`);
  console.table(rows.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]]))));
}
